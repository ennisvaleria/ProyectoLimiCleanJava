    private void btnGuardadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardadActionPerformed
        String Nombre = txtNombre.getText().trim();
        String Apellido = txtApellido.getText().trim();
        String usuario = txtUsuario.getText().trim();
        String correo = txtCorreo.getText().trim();
        String Telefono = txtTelefono.getText().trim();
        String rol = cmboxRol.getSelectedItem().toString();
        String Direccion = txtDireccion.getText().trim();

        String password1 = String.valueOf(txtpassword1.getPassword());
        String password2 = String.valueOf(txtpassword2.getPassword());

        if (Nombre.isEmpty()
                || Apellido.isEmpty()
                || usuario.isEmpty()
                || correo.isEmpty()
                || Telefono.isEmpty()
                || Direccion.isEmpty()
                || password1.isEmpty()
                || password2.isEmpty()) {

            JOptionPane.showMessageDialog(
                    null,
                    "Todos los campos son obligatorios."
            );
            return;
        }

        if (!password1.equals(password2)) {

            JOptionPane.showMessageDialog(
                    null,
                    "Las contraseñas no coinciden."
            );
            return;
        }

        int idEmpleado = Funciones_BD.insertarEmpleado(
                ConexionBD.obtenerConexion(),
                rol,
                Nombre,
                Apellido,
                usuario,
                password1,
                correo,
                Direccion,
                Telefono
        );

        if (idEmpleado > 0) {

            JOptionPane.showMessageDialog(
                    null,
                    "Empleado registrado correctamente.\nID: " + idEmpleado
            );

            txtNombre.setText("");
            txtApellido.setText("");
            txtUsuario.setText("");
            txtCorreo.setText("");
            txtTelefono.setText("");
            txtDireccion.setText("");
            txtpassword1.setText("");
            txtpassword2.setText("");

            cmboxRol.setSelectedIndex(0);

            txtNombre.requestFocus();

        } else {

            JOptionPane.showMessageDialog(
                    null,
                    "No se pudo registrar el empleado."
            );
        }
    }//GEN-LAST:event_btnGuardadActionPerformed

